import { mkdir, readFile, writeFile } from "node:fs/promises";
import sharp from "sharp";

// Only the mark and wordmark masters are edited; every platform asset derives from them.
const [mark, wordmark] = await Promise.all(
  ["mark", "wordmark"].map((name) =>
    readFile(`assets/brand/fauxgo-${name}.svg`, "utf8"),
  ),
);
const pathFrom = (svg) => {
  const path = svg.match(/<path\b[^>]*\bd="([^"]+)"/);
  if (!path) throw new Error("Brand master must contain an outlined SVG path.");
  return path[1];
};
const markPath = pathFrom(mark);
const wordmarkPath = pathFrom(wordmark);
const colors = { coral: "#C94332", ink: "#20201F", paper: "#FCFBF8" };
const markArt = (fill = colors.coral) =>
  `<path fill="${fill}" d="${markPath}"/>`;
const wordArt = (fill = colors.ink) =>
  `<path fill="${fill}" fill-rule="evenodd" d="${wordmarkPath}"/>`;
const svg = (width, height, title, artwork) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" role="img" aria-labelledby="title"><title id="title">${title}</title>${artwork}</svg>\n`;
const lockup = `${markArt()}<g transform="translate(80 8)">${wordArt()}</g>`;
const icon = svg(
  1024,
  1024,
  "FauxGo app icon",
  `<rect width="1024" height="1024" fill="${colors.coral}"/><g transform="translate(160 160) scale(11)">${markArt(colors.paper)}</g>`,
);
const foreground = svg(
  1024,
  1024,
  "FauxGo adaptive icon foreground",
  `<g transform="translate(192 192) scale(10)">${markArt(colors.paper)}</g>`,
);
const favicon = svg(
  64,
  64,
  "FauxGo favicon",
  `<rect width="64" height="64" rx="14" fill="${colors.coral}"/><g transform="translate(6 6) scale(0.8125)">${markArt(colors.paper)}</g>`,
);
const social = svg(
  1200,
  630,
  "FauxGo — All the journey. None of the going.",
  `<rect width="1200" height="630" fill="${colors.paper}"/><g transform="translate(88 74) scale(1.5)">${lockup}</g><text x="88" y="318" fill="${colors.ink}" font-family="Arial, sans-serif" font-size="64" font-weight="700" letter-spacing="-2">All the journey.</text><text x="88" y="394" fill="${colors.ink}" font-family="Arial, sans-serif" font-size="64" font-weight="700" letter-spacing="-2">None of the going.</text><text x="90" y="456" fill="#706D68" font-family="Arial, sans-serif" font-size="25">On-demand experiences, imagined. Entertainment only.</text><path d="M88 512H1112" stroke="#E6E2DD"/><text x="90" y="557" fill="#706D68" font-family="Arial, sans-serif" font-size="22">Made by Kaizun Labs</text><g transform="translate(888 194) scale(3.5)">${markArt()}</g>`,
);

await mkdir("public/brand", { recursive: true });
await writeFile(
  "src/constants/brand.generated.ts",
  `// Generated by npm run brand:generate from assets/brand SVG masters.\nexport const brandMarkPath = ${JSON.stringify(markPath)};\nexport const brandWordmarkPath = ${JSON.stringify(wordmarkPath)};\n`,
);
await Promise.all([
  writeFile(
    "assets/brand/fauxgo-mark-mono.svg",
    svg(64, 64, "FauxGo parallel passage mark", markArt("currentColor")),
  ),
  writeFile(
    "assets/brand/fauxgo-horizontal.svg",
    svg(280, 64, "FauxGo", lockup),
  ),
  writeFile("assets/brand/fauxgo-icon.svg", icon),
  writeFile("assets/brand/fauxgo-adaptive-foreground.svg", foreground),
  writeFile("assets/brand/fauxgo-og.svg", social),
  writeFile("public/brand/fauxgo-favicon.svg", favicon),
]);
const jobs = [
  [icon, "assets/images/fauxgo-icon.png", 1024],
  [foreground, "assets/images/fauxgo-adaptive-foreground.png", 1024],
  [foreground, "assets/images/fauxgo-monochrome.png", 1024],
  [mark, "assets/images/fauxgo-splash.png", 512],
  [
    mark.replace(colors.coral, "#F58B79"),
    "assets/images/fauxgo-splash-dark.png",
    512,
  ],
  [favicon, "assets/images/favicon.png", 64],
  [icon, "public/brand/apple-touch-icon.png", 180],
  [social, "assets/images/fauxgo-og.png", 1200, 630],
  [social, "public/brand/fauxgo-og.png", 1200, 630],
];
await Promise.all(
  jobs.map(([source, destination, width, height = width]) =>
    sharp(Buffer.from(source))
      .resize(width, height)
      .png({ compressionLevel: 9 })
      .toFile(destination),
  ),
);
console.log(
  `Generated vector lockups, shared UI paths and ${jobs.length} platform images.`,
);
