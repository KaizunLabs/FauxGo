import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import prettier from "prettier";
import sharp from "sharp";

const root = process.cwd();
const photographyRoot = path.join(root, "assets/photography");
const sourceRoot = path.join(photographyRoot, "source");
const derivedRoot = path.join(photographyRoot, "derived");
const provenance = JSON.parse(
  await readFile(path.join(photographyRoot, "provenance.json"), "utf8"),
);
const provenanceById = new Map(
  provenance.map((entry) => [entry.assetId, entry]),
);

async function sourceFiles(directory) {
  const found = [];
  for (const entry of await readdir(directory, { withFileTypes: true }).catch(
    () => [],
  )) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) found.push(...(await sourceFiles(absolute)));
    else if (/-master\.(?:png|jpe?g|webp)$/i.test(entry.name))
      found.push(absolute);
  }
  return found;
}

const originalSources = (
  await readdir(photographyRoot, { withFileTypes: true })
)
  .filter(
    (entry) =>
      entry.isFile() && /-master\.(?:png|jpe?g|webp)$/i.test(entry.name),
  )
  .map((entry) => path.join(photographyRoot, entry.name));
const stockSources = await sourceFiles(sourceRoot);
const sources = [...originalSources, ...stockSources].sort();
const variants = [
  ["thumb", 240],
  ["card", 640],
  ["hero", 1280],
];
const runtime = {};
let bytes = 0;

for (const source of sources) {
  const id = path.basename(source).replace(/-master\.(?:png|jpe?g|webp)$/i, "");
  const metadata = provenanceById.get(id);
  if (!metadata) throw new Error(`Missing provenance for ${id}`);
  const isStock = source.startsWith(sourceRoot + path.sep);
  const outputDirectory = isStock ? derivedRoot : photographyRoot;
  await mkdir(outputDirectory, { recursive: true });
  runtime[id] = {};
  for (const [suffix, width] of variants) {
    const destination = path.join(outputDirectory, `${id}-${suffix}.webp`);
    const info = await sharp(source)
      .rotate()
      .resize(width, Math.round((width * 2) / 3), {
        fit: "cover",
        position: "attention",
      })
      .webp({ quality: suffix === "hero" ? 78 : 80, effort: 4 })
      .toFile(destination);
    bytes += info.size;
    runtime[id][suffix] = path
      .relative(path.join(root, "src/data"), destination)
      .split(path.sep)
      .join("/");
  }
}

const entries = Object.keys(runtime)
  .sort()
  .map((id) => {
    const metadata = provenanceById.get(id);
    const files = runtime[id];
    return `  ${JSON.stringify(id)}: {
    thumb: require(${JSON.stringify(files.thumb)}),
    card: require(${JSON.stringify(files.card)}),
    hero: require(${JSON.stringify(files.hero)}),
    description: ${JSON.stringify(metadata.alt)},
    tags: ${JSON.stringify(metadata.tags)},
    sourceId: ${JSON.stringify(
      metadata.source === "pexels"
        ? `pexels:${metadata.pexelsPhotoId}`
        : metadata.source,
    )},
    fallbackClass: ${JSON.stringify(metadata.usage)},
  }`;
  });
const photographySource = `// Generated by scripts/optimize-photography.mjs. Do not edit manually.
export const generatedPhotography = {
${entries.join(",\n")}
} as const;
`;
await writeFile(
  path.join(root, "src/data/photography.generated.ts"),
  await prettier.format(photographySource, { parser: "typescript" }),
);

const metadataSource = `// Generated by scripts/optimize-photography.mjs. Do not edit manually.
export const photoMetadata = ${JSON.stringify(
  provenance
    .map((entry) => ({
      id: entry.assetId,
      tags: entry.tags,
      usage: entry.usage,
      source: entry.source,
      scope: entry.scope ?? "exact",
    }))
    .sort((a, b) => a.id.localeCompare(b.id)),
  null,
  2,
)} as const;
`;
await writeFile(
  path.join(root, "src/data/photo-metadata.generated.ts"),
  await prettier.format(metadataSource, { parser: "typescript" }),
);

console.log(
  `Optimized ${sources.length} photos into ${sources.length * variants.length} derivatives (${Math.round(
    bytes / 1024,
  )} KiB runtime assets).`,
);
